export function canTransitionOrder(from: OrderStatus, to: OrderStatus) { return transitions[from].includes(to); }
const workflowManagedStatuses = new Set<OrderStatus>(["SHIPPING_QUOTE_PENDING_CUSTOMER_APPROVAL", "SHIPPING_QUOTE_READY", "SHIPPING_PAYMENT_PENDING"]);
export function getAllowedOrderTransitions(from: OrderStatus) { if (from === "SHIPPING_QUOTE_READY" || from === "SHIPPING_PAYMENT_PENDING") return []; return transitions[from].filter((status) => !workflowManagedStatuses.has(status)); }
